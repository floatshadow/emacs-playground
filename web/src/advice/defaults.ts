/** Uses each index table when it is non-empty, else the built-in default. */
export function withDefaultTables(t: Partial<Tables> | null | undefined): Tables {
  const nonEmpty = <T extends object>(v: T | null | undefined): v is T =>
    v != null && (Array.isArray(v) ? v.length > 0 : Object.keys(v).length > 0)
  return {
    exits: nonEmpty(t?.exits) ? t.exits : DEFAULT_EXITS,
    habits: nonEmpty(t?.habits) ? t.habits : DEFAULT_HABITS,
    gloss: nonEmpty(t?.gloss) ? t.gloss : DEFAULT_GLOSS,
    cheats: nonEmpty(t?.cheats) ? t.cheats : DEFAULT_CHEATS,
    glossary: nonEmpty(t?.glossary) ? t.glossary : DEFAULT_GLOSSARY,
  }
}
