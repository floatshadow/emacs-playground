// Package tsgen generates web/src/protocol.gen.ts from internal/protocol
// (api.md §8, backend.md §4 `playctl protocol typescript`).
//
// It reflects over the protocol types for structure and JSON names, and
// parses the protocol package source for enum constants and doc comments.
// This replaces the invopop/jsonschema + json-schema-to-typescript pipeline
// sketched in api.md §8: going direct yields discriminated unions for events,
// string-literal enums and an RPC operation map, with no Node step in the Go
// build. JSON Schema is still generated with invopop/jsonschema for the
// configuration file (`playctl config schema`).
package tsgen

import (
	"bytes"
	"encoding/json"
	"fmt"
	"go/ast"
	"go/constant"
	"go/parser"
	"go/token"
	"go/types"
	"os"
	"path/filepath"
	"reflect"
	"sort"
	"strconv"
	"strings"

	"github.com/zsy/emacs-playground/internal/protocol"
)

// Header starts the generated file.
const Header = "// Code generated by `playctl protocol typescript` from internal/protocol. DO NOT EDIT.\n// Regenerate: go run ./cmd/playctl protocol typescript -o web/src/protocol.gen.ts\n"

// custom maps types with custom JSON to their TypeScript form.
var custom = map[reflect.Type]string{
	reflect.TypeOf(protocol.Layout{}):    `number | [SplitKind, ...Layout[]] | null`,
	reflect.TypeOf(protocol.LocalText{}): `string | Record<string, string>`,
	reflect.TypeOf(protocol.Truth(0)):    `boolean | "unknown"`,
	reflect.TypeOf(protocol.Predicate{}): `Record<string, unknown>`,
	reflect.TypeOf(protocol.CheatRow{}):  `[keys: string, description: string]`,
}

var rawMessage = reflect.TypeOf(json.RawMessage{})

// roots lists the entry points; everything reachable is emitted.
func roots() []any {
	r := []any{
		protocol.Problem{}, protocol.PtyControl{}, protocol.EventsClientMessage{},
		protocol.HealthStatus{}, protocol.PreviewListing{},
		protocol.Me{}, protocol.AuthConfigInfo{}, protocol.InviteLoginRequest{},
		protocol.SessionInfo{}, protocol.Progress{}, protocol.ProgressResetRequest{},
		protocol.StuckRequest{}, protocol.Created{}, protocol.ProgressReport{},
		protocol.InternalStuckReport{}, protocol.Heartbeat{},
		protocol.CurriculumIndex{}, protocol.LessonBundle{}, protocol.Scenario{},
		protocol.DemoToken{}, protocol.WindowSpec{}, protocol.ExitSession{},
		protocol.AgentHelloMsg{}, protocol.AgentFrameMsg{}, protocol.AgentPingMsg{},
		protocol.AgentReplyMsg{}, protocol.AgentCallMsg{}, protocol.AgentPongMsg{},
		protocol.AgentCheckResult{},
		protocol.Config{},
	}
	for _, t := range protocol.EventTypes {
		r = append(r, reflect.ValueOf(protocol.NewEvent(t)).Elem().Interface())
	}
	for _, s := range protocol.RPCSpecs {
		r = append(r, s.Request, s.Result)
	}
	return r
}

type gen struct {
	src     *source
	named   map[string]reflect.Type
	order   []string
	enumUse map[string]bool
}

// Generate renders the TypeScript file. srcDir is the protocol package
// directory (for enum values and comments).
func Generate(srcDir string) ([]byte, error) {
	src, err := parseSource(srcDir)
	if err != nil {
		return nil, err
	}
	g := &gen{src: src, named: map[string]reflect.Type{}, enumUse: map[string]bool{}}
	for _, r := range roots() {
		g.visit(reflect.TypeOf(r))
	}
	// Always emit SplitKind (used by the custom Layout form).
	g.enumUse["SplitKind"] = true

	var b bytes.Buffer
	b.WriteString(Header)
	b.WriteString("/* eslint-disable */\n\n")

	// Enums.
	enumNames := make([]string, 0, len(src.enums))
	for n := range src.enums {
		enumNames = append(enumNames, n)
	}
	sort.Strings(enumNames)
	for _, n := range enumNames {
		vals := src.enums[n]
		writeDoc(&b, src.typeDocs[n], "")
		quoted := make([]string, len(vals))
		for i, v := range vals {
			quoted[i] = strconv.Quote(v.value)
		}
		fmt.Fprintf(&b, "export type %s = %s;\n", n, strings.Join(quoted, " | "))
		for _, v := range vals {
			fmt.Fprintf(&b, "export const %s = %s satisfies %s;\n", v.name, strconv.Quote(v.value), n)
		}
		b.WriteString("\n")
	}

	// Custom-JSON types.
	customNames := []string{}
	for t := range custom {
		customNames = append(customNames, t.Name())
	}
	sort.Strings(customNames)
	for _, n := range customNames {
		for t, ts := range custom {
			if t.Name() == n {
				writeDoc(&b, src.typeDocs[n], "")
				fmt.Fprintf(&b, "export type %s = %s;\n\n", n, ts)
			}
		}
	}

	// Structs.
	names := append([]string(nil), g.order...)
	sort.Strings(names)
	for _, n := range names {
		g.writeStruct(&b, n, g.named[n])
	}

	// Event union and RPC map.
	var evs []string
	for _, t := range protocol.EventTypes {
		evs = append(evs, reflect.TypeOf(protocol.NewEvent(t)).Elem().Name())
	}
	b.WriteString("/** Every event on /s/{id}/events, discriminated by `t` (api.md §4). */\n")
	fmt.Fprintf(&b, "export type Event = %s;\n\n", strings.Join(evs, " | "))
	b.WriteString("/** Session RPC success body (api.md §3.4). */\nexport interface RpcOk<T> {\n  ok: true;\n  result: T;\n}\n\n")
	b.WriteString("/** Request and result types per session RPC op: POST /s/{id}/rpc/{op}. */\nexport interface RpcOps {\n")
	for _, s := range protocol.RPCSpecs {
		fmt.Fprintf(&b, "  %s: { request: %s; result: %s };\n", strconv.Quote(string(s.Op)),
			reflect.TypeOf(s.Request).Name(), reflect.TypeOf(s.Result).Name())
	}
	b.WriteString("}\n\n")

	// Plain constants.
	b.WriteString("// Constants.\n")
	for _, c := range src.consts {
		fmt.Fprintf(&b, "export const %s = %s;\n", c.name, c.value)
	}
	return b.Bytes(), nil
}

func (g *gen) visit(t reflect.Type) {
	for t.Kind() == reflect.Pointer || t.Kind() == reflect.Slice || t.Kind() == reflect.Array || t.Kind() == reflect.Map {
		if _, ok := custom[t]; ok || t == rawMessage {
			return
		}
		t = t.Elem()
	}
	if _, ok := custom[t]; ok {
		return
	}
	if t.Kind() != reflect.Struct || t.Name() == "" {
		return
	}
	if _, ok := g.named[t.Name()]; ok {
		return
	}
	g.named[t.Name()] = t
	g.order = append(g.order, t.Name())
	for i := 0; i < t.NumField(); i++ {
		f := t.Field(i)
		if f.Anonymous {
			g.visit(f.Type)
			continue
		}
		if f.IsExported() {
			g.visit(f.Type)
		}
	}
}

type field struct {
	name     string
	ts       string
	optional bool
	doc      string
}

func (g *gen) fields(t reflect.Type, owner string) []field {
	var out []field
	for i := 0; i < t.NumField(); i++ {
		f := t.Field(i)
		if f.Anonymous && f.Type.Kind() == reflect.Struct {
			out = append(out, g.fields(f.Type, f.Type.Name())...)
			continue
		}
		if !f.IsExported() {
			continue
		}
		tag := f.Tag.Get("json")
		if tag == "-" {
			continue
		}
		name, opts, _ := strings.Cut(tag, ",")
		if name == "" {
			name = f.Name
		}
		omit := strings.Contains(opts, "omitempty")
		out = append(out, field{
			name:     name,
			ts:       g.tsType(f.Type, !omit),
			optional: omit,
			doc:      g.src.fieldDocs[owner+"."+f.Name],
		})
	}
	return out
}

func (g *gen) tsType(t reflect.Type, nullablePtr bool) string {
	if ts, ok := custom[t]; ok {
		if t.Name() != "" {
			return t.Name()
		}
		return ts
	}
	if t == rawMessage {
		return "unknown"
	}
	if t.PkgPath() == "github.com/zsy/emacs-playground/internal/protocol" && t.Kind() == reflect.String {
		if _, ok := g.src.enums[t.Name()]; ok {
			return t.Name()
		}
	}
	switch t.Kind() {
	case reflect.Pointer:
		inner := g.tsType(t.Elem(), nullablePtr)
		if nullablePtr {
			return inner + " | null"
		}
		return inner
	case reflect.String:
		return "string"
	case reflect.Bool:
		return "boolean"
	case reflect.Int, reflect.Int8, reflect.Int16, reflect.Int32, reflect.Int64,
		reflect.Uint, reflect.Uint8, reflect.Uint16, reflect.Uint32, reflect.Uint64,
		reflect.Float32, reflect.Float64:
		return "number"
	case reflect.Slice, reflect.Array:
		el := g.tsType(t.Elem(), false)
		if strings.Contains(el, "|") {
			el = "(" + el + ")"
		}
		return el + "[]"
	case reflect.Map:
		return "Record<string, " + g.tsType(t.Elem(), false) + ">"
	case reflect.Interface:
		return "unknown"
	case reflect.Struct:
		if t.Name() == "" {
			return "Record<string, never>"
		}
		return t.Name()
	}
	return "unknown"
}

func (g *gen) writeStruct(b *bytes.Buffer, name string, t reflect.Type) {
	writeDoc(b, g.src.typeDocs[name], "")
	fs := g.fields(t, name)
	// Events and State: narrow t to the literal.
	lit := ""
	if v, ok := reflect.New(t).Interface().(protocol.Event); ok {
		lit = strconv.Quote(string(v.Type()))
	}
	if len(fs) == 0 {
		fmt.Fprintf(b, "export type %s = Record<string, never>;\n\n", name)
		return
	}
	fmt.Fprintf(b, "export interface %s {\n", name)
	for _, f := range fs {
		writeDoc(b, f.doc, "  ")
		ts := f.ts
		opt := ""
		if f.optional {
			opt = "?"
		}
		if f.name == "t" && lit != "" {
			ts, opt = lit, ""
		}
		key := f.name
		if !isIdent(key) {
			key = strconv.Quote(key)
		}
		fmt.Fprintf(b, "  %s%s: %s;\n", key, opt, ts)
	}
	b.WriteString("}\n\n")
}

func isIdent(s string) bool {
	for i, r := range s {
		if !(r == '_' || r == '$' || (r >= 'a' && r <= 'z') || (r >= 'A' && r <= 'Z') || (i > 0 && r >= '0' && r <= '9')) {
			return false
		}
	}
	return s != ""
}

func writeDoc(b *bytes.Buffer, doc, indent string) {
	doc = strings.TrimSpace(doc)
	if doc == "" {
		return
	}
	doc = strings.ReplaceAll(doc, "*/", "*\\/")
	lines := strings.Split(doc, "\n")
	if len(lines) == 1 {
		fmt.Fprintf(b, "%s/** %s */\n", indent, lines[0])
		return
	}
	fmt.Fprintf(b, "%s/**\n", indent)
	for _, l := range lines {
		if l == "" {
			fmt.Fprintf(b, "%s *\n", indent)
		} else {
			fmt.Fprintf(b, "%s * %s\n", indent, l)
		}
	}
	fmt.Fprintf(b, "%s */\n", indent)
}

type enumVal struct{ name, value string }
type constVal struct{ name, value string }

type source struct {
	enums     map[string][]enumVal
	consts    []constVal
	typeDocs  map[string]string
	fieldDocs map[string]string
}

func parseSource(dir string) (*source, error) {
	fset := token.NewFileSet()
	entries, err := os.ReadDir(dir)
	if err != nil {
		return nil, fmt.Errorf("tsgen: %w", err)
	}
	var files []*ast.File
	for _, e := range entries {
		n := e.Name()
		if e.IsDir() || !strings.HasSuffix(n, ".go") || strings.HasSuffix(n, "_test.go") {
			continue
		}
		f, err := parser.ParseFile(fset, filepath.Join(dir, n), nil, parser.ParseComments)
		if err != nil {
			return nil, fmt.Errorf("tsgen: parse: %w", err)
		}
		if f.Name.Name != "protocol" {
			continue
		}
		files = append(files, f)
	}
	if len(files) == 0 {
		return nil, fmt.Errorf("tsgen: no package protocol in %s", dir)
	}
	// Type-check (stdlib only) to get constant values and types.
	conf := types.Config{Importer: importerFor(fset)}
	info := &types.Info{Defs: map[*ast.Ident]types.Object{}}
	if _, err := conf.Check("github.com/zsy/emacs-playground/internal/protocol", fset, files, info); err != nil {
		return nil, fmt.Errorf("tsgen: typecheck: %w", err)
	}
	s := &source{enums: map[string][]enumVal{}, typeDocs: map[string]string{}, fieldDocs: map[string]string{}}
	for _, f := range files {
		for _, d := range f.Decls {
			gd, ok := d.(*ast.GenDecl)
			if !ok {
				continue
			}
			for _, sp := range gd.Specs {
				switch spec := sp.(type) {
				case *ast.TypeSpec:
					doc := spec.Doc.Text()
					if doc == "" && len(gd.Specs) == 1 {
						doc = gd.Doc.Text()
					}
					s.typeDocs[spec.Name.Name] = doc
					if st, ok := spec.Type.(*ast.StructType); ok {
						for _, fl := range st.Fields.List {
							txt := fl.Doc.Text()
							if txt == "" {
								txt = fl.Comment.Text()
							}
							for _, n := range fl.Names {
								s.fieldDocs[spec.Name.Name+"."+n.Name] = txt
							}
						}
					}
				case *ast.ValueSpec:
					if gd.Tok != token.CONST {
						continue
					}
					for _, n := range spec.Names {
						obj, ok := info.Defs[n].(*types.Const)
						if !ok || !n.IsExported() {
							continue
						}
						if named, ok := obj.Type().(*types.Named); ok {
							if b, ok := named.Underlying().(*types.Basic); ok && b.Info()&types.IsString != 0 {
								s.enums[named.Obj().Name()] = append(s.enums[named.Obj().Name()],
									enumVal{name: n.Name, value: constant.StringVal(obj.Val())})
								continue
							}
							if named.Obj().Name() == "Truth" || named.Obj().Name() == "Modifiers" {
								continue
							}
						}
						switch obj.Val().Kind() {
						case constant.String:
							s.consts = append(s.consts, constVal{n.Name, strconv.Quote(constant.StringVal(obj.Val()))})
						case constant.Int, constant.Float:
							s.consts = append(s.consts, constVal{n.Name, obj.Val().ExactString()})
						}
					}
				}
			}
		}
	}
	return s, nil
}
